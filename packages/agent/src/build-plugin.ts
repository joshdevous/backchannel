#!/usr/bin/env bun
/**
 * Builds the Claude Code plugin in `plugin/` from this package.
 *
 * Claude Code copies only the plugin directory into its cache, so the plugin cannot import
 * `packages/agent` or `packages/core` at runtime. We bundle our own code into `plugin/server.js`
 * and `plugin/setup.js` and leave npm packages external; the plugin's package.json lists them and
 * gets them installed the same way as Anthropic's official Discord plugin (`bun install` on start,
 * plus Claude Code's own install from `bun.lock`).
 *
 *   bun run --cwd packages/agent build:plugin
 *
 * `test/plugin-bundle.test.ts` fails when the committed bundle is out of date.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const agentDir = join(import.meta.dir, '..');
export const pluginDir = join(agentDir, '..', '..', 'plugin');

const BANNER = '// Generated by packages/agent/src/build-plugin.ts from packages/agent and packages/core. Do not edit.';

interface AgentPackage {
  dependencies: Record<string, string>;
}

/** npm dependencies of the agent, which the plugin installs itself (workspace packages get bundled). */
export function pluginDependencies(): Record<string, string> {
  const pkg = JSON.parse(readFileSync(join(agentDir, 'package.json'), 'utf8')) as AgentPackage;
  return Object.fromEntries(Object.entries(pkg.dependencies).filter(([, version]) => !version.startsWith('workspace:')));
}

/** Returns `{ 'server.js': code, 'setup.js': code }` without writing anything. */
export async function bundle(): Promise<Record<string, string>> {
  const external = Object.keys(pluginDependencies());
  const outputs: Record<string, string> = {};
  for (const [entry, outName] of [['index.ts', 'server.js'], ['setup.ts', 'setup.js']] as const) {
    const result = await Bun.build({
      entrypoints: [join(agentDir, 'src', entry)],
      target: 'bun',
      format: 'esm',
      external,
      banner: BANNER,
    });
    if (!result.success) throw new AggregateError(result.logs, `Bundling ${entry} failed`);
    // Bun labels each module with its path relative to the cwd; drop those so output is the same wherever it is built.
    outputs[outName] = (await result.outputs[0]!.text()).replace(/^\/\/ \S+\.ts\n/gm, '');
  }
  return outputs;
}

if (import.meta.main) {
  for (const [name, code] of Object.entries(await bundle())) {
    writeFileSync(join(pluginDir, name), code);
    console.log(`wrote plugin/${name}`);
  }
  const pkgPath = join(pluginDir, 'package.json');
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8')) as AgentPackage;
  pkg.dependencies = pluginDependencies();
  writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
  // Refresh plugin/bun.lock: Claude Code only installs plugin dependencies from a lockfile.
  const install = Bun.spawnSync(['bun', 'install'], { cwd: pluginDir, stdout: 'inherit', stderr: 'inherit' });
  if (install.exitCode !== 0) process.exit(install.exitCode ?? 1);
}
